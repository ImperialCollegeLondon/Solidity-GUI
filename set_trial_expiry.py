#!/usr/bin/env python
"""Generates the setup_trial_expiry.py file.

This is used as a runtime hook by Pyinstaller to enforce an expiry date for the program.
"""
import sys
from datetime import date, timedelta
from pathlib import Path

if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Error: Must provide trial period in days as an argument")
        sys.exit(1)

    expiry_date = date.today() + timedelta(days=float(sys.argv[1]))
    print(f"The program is set to expire on {expiry_date.strftime('%d %b %Y')}.")

    my_dir = Path(__file__).parent.absolute()
    output_path = my_dir / "setup_trial_expiry.py"
    print(f"Writing to {output_path}")
    with output_path.open("w") as f:
        f.write(
            f'"""This script was auto-generated by {Path(__file__).name}."""\n\n'
            "from solidity_gui import config\n"
            "import datetime\n\n"
            f"config.TRIAL_EXPIRY_DATE = {repr(expiry_date)}\n"
        )
