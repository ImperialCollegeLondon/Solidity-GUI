#!/usr/bin/env python
"""Generates the setup_mac_address_verification.py file.

This is used as a runtime hook by Pyinstaller to enforce MAC address verification.
"""
import json
import sys
from pathlib import Path

if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(
            "Error: Must provide JSON string of key/value pairs of "
            "MAC addresses and expiry dates."
        )
        sys.exit(1)

    mac_addresses = sys.argv[1]
    print(f"The program is set to allow the following MAC addresses {mac_addresses}.")

    project_dir = Path(__file__).parent.absolute()
    output_path = project_dir / "setup_mac_address_verification.py"
    print(f"Writing to {output_path}")
    with output_path.open("w") as f:
        f.write(
            f'"""This script was auto-generated by {Path(__file__).name}."""\n\n'
            "from solidity_gui import config\n"
            f"config.ALLOWED_MAC_ADDRESSES = {json.loads(mac_addresses)}\n"
        )
